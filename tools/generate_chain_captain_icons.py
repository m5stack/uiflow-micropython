"""Generate the launcher's native-size, antialiased Wi-Fi PNG resources.

Uses only the standard library. Each pixel averages 16x16 samples; the device
decodes the finished 20x14 image without scaling or allocating a large sprite.
"""

import math
from pathlib import Path
import struct
import zlib

WIDTH, HEIGHT, SAMPLES = 20, 14, 16
BG, ACCENT, MUTED, LINE = 0xFFFFFF, 0x1769E0, 0x6B7482, 0xDDE0E8


def rgb(color):
    return (color >> 16, (color >> 8) & 255, color & 255)


def segment_distance(x, y, x1, y1, x2, y2):
    dx, dy = x2 - x1, y2 - y1
    t = max(0, min(1, ((x - x1) * dx + (y - y1) * dy) / (dx * dx + dy * dy)))
    return math.hypot(x - x1 - t * dx, y - y1 - t * dy)


def sample(x, y, level, disconnected):
    color = BG
    dx, dy = x - 10, y - 12.5
    angle = math.degrees(math.atan2(dy, dx)) % 360
    radius = math.hypot(dx, dy)
    for index, arc_radius in enumerate((3.8, 7.65, 11.5)):
        stroke = 225 <= angle <= 315 and abs(radius - arc_radius) <= 0.75
        for end in (225, 315):
            a = math.radians(end)
            stroke |= (
                math.hypot(dx - arc_radius * math.cos(a), dy - arc_radius * math.sin(a))
                <= 0.75
            )
        if stroke:
            color = ACCENT if index < level else LINE
    if radius <= 1.2:
        color = ACCENT if level else MUTED
    if disconnected and segment_distance(x, y, 3, 2, 17, 13) <= 0.65:
        color = MUTED
    return rgb(color)


def render(level, disconnected=False):
    pixels = bytearray()
    for y in range(HEIGHT):
        pixels.append(0)  # PNG filter: none
        for x in range(WIDTH):
            total = [0, 0, 0]
            for sy in range(SAMPLES):
                for sx in range(SAMPLES):
                    pixel = sample(
                        x + (sx + 0.5) / SAMPLES,
                        y + (sy + 0.5) / SAMPLES,
                        level,
                        disconnected,
                    )
                    for channel in range(3):
                        total[channel] += pixel[channel]
            pixels.extend(round(value / (SAMPLES * SAMPLES)) for value in total)

    def chunk(kind, data):
        return (
            struct.pack(">I", len(data))
            + kind
            + data
            + struct.pack(">I", zlib.crc32(kind + data))
        )

    return (
        b"\x89PNG\r\n\x1a\n"
        + chunk(b"IHDR", struct.pack(">IIBBBBB", WIDTH, HEIGHT, 8, 2, 0, 0, 0))
        + chunk(b"IDAT", zlib.compress(pixels, 9))
        + chunk(b"IEND", b"")
    )


def main():
    target = (
        Path(__file__).resolve().parents[1]
        / "m5stack/modules/startup/chain_captain_icons.py"
    )
    lines = [
        "# SPDX-FileCopyrightText: 2026 M5Stack Technology CO LTD",
        "# SPDX-License-Identifier: MIT",
        '"""Generated by tools/generate_chain_captain_icons.py; do not edit."""',
        "",
        "# Levels 0..3, then disconnected. Native dimensions: 20x14 pixels.",
        "WIFI_ICONS = (",
    ]
    for level, disconnected in [(level, False) for level in range(4)] + [(0, True)]:
        data = render(level, disconnected)
        lines.append("    (")
        for offset in range(0, len(data), 32):
            lines.append("        " + repr(data[offset : offset + 32]))
        lines.append("    ),")
    lines.append(")\n")
    target.write_text("\n".join(lines), encoding="utf-8")
    print(target)


if __name__ == "__main__":
    main()
